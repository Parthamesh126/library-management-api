package com.symphonyai.library.service;

import com.symphonyai.library.dto.AuthorRequest;
import com.symphonyai.library.dto.AuthorResponse;
import com.symphonyai.library.entity.Author;
import com.symphonyai.library.exception.DuplicateResourceException;
import com.symphonyai.library.exception.ResourceNotFoundException;
import com.symphonyai.library.repository.AuthorRepository;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class AuthorServiceImplTest {

    @Mock
    private AuthorRepository authorRepository;

    @InjectMocks
    private AuthorServiceImpl authorService;

    private Author author;

    @BeforeEach
    void setUp() {
        author = new Author();
        author.setName("Robert Martin");
        author.setEmail("robert@example.com");
    }

    @Test
    void createAuthorSuccessfully() {
        when(authorRepository.existsByEmail("robert@example.com"))
                .thenReturn(false);

        when(authorRepository.save(any(Author.class)))
                .thenAnswer(invocation -> {
                    Author saved = invocation.getArgument(0);

                    // Simulate the ID generated by the database.
                    // This is a unit test, not a real database insert.
                    return saved;
                });

        AuthorResponse response = authorService.create(
                new AuthorRequest("Robert Martin", "robert@example.com"));

        assertEquals("Robert Martin", response.name());
        assertEquals("robert@example.com", response.email());

        verify(authorRepository).save(any(Author.class));
    }

    @Test
    void createAuthorRejectsDuplicateEmail() {
        when(authorRepository.existsByEmail("robert@example.com"))
                .thenReturn(true);

        assertThrows(
                DuplicateResourceException.class,
                () -> authorService.create(
                        new AuthorRequest(
                                "Robert Martin",
                                "robert@example.com"))
        );

        verify(authorRepository, never()).save(any(Author.class));
    }

    @Test
    void findAuthorByIdThrowsWhenMissing() {
        when(authorRepository.findById(99L))
                .thenReturn(Optional.empty());

        assertThrows(
                ResourceNotFoundException.class,
                () -> authorService.findById(99L)
        );
    }

    @Test
    void updateAuthorSuccessfully() {
        when(authorRepository.findById(1L))
                .thenReturn(Optional.of(author));

        when(authorRepository.existsByEmailAndIdNot(
                "updated@example.com", 1L))
                .thenReturn(false);

        when(authorRepository.save(any(Author.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        AuthorResponse response = authorService.update(
                1L,
                new AuthorRequest(
                        "Updated Author",
                        "updated@example.com"));

        assertEquals("Updated Author", response.name());
        assertEquals("updated@example.com", response.email());
    }
}
